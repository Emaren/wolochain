func digest(raw []byte) string  { h := sha256.Sum256(raw); return hex.EncodeToString(h[:]) }
func validDigest(s string) bool { return digestPattern.MatchString(s) && strings.Trim(s, "0") != "" }
func publicKey(s string) (ed25519.PublicKey, error) {
	b, e := hex.DecodeString(s)
	if e != nil || len(b) != ed25519.PublicKeySize || hex.EncodeToString(b) != s || bytes.Equal(b, make([]byte, 32)) {
		return nil, errHeld
	}
	return ed25519.PublicKey(b), nil
}
func validPath(s string) bool {
	return filepath.IsAbs(s) && filepath.Clean(s) == s && !strings.ContainsRune(s, 0)
}
func validPGHost(host string) bool {
	if net.ParseIP(host) != nil {
		return true
	}
	if host == "" || len(host) > 253 {
		return false
	}
	for _, label := range strings.Split(host, ".") {
		if !hostLabelPattern.MatchString(label) {
			return false
		}
	}
	return true
}
func validAddress(s string) bool {
	if s != strings.ToLower(s) {
		return false
	}
	h, w, e := bech32.Decode(s, 90)
	if e != nil || h != "wolo" {
		return false
	}
	b, e := bech32.ConvertBits(w, 5, 8, false)
	return e == nil && len(b) == 20
}
func positive(s string, max uint64) bool {
	if s == "" || s[0] < '1' || s[0] > '9' {
		return false
	}
	for _, c := range s {
		if c < '0' || c > '9' {
			return false
		}
	}
	n, e := strconv.ParseUint(s, 10, 64)
	return e == nil && n > 0 && n <= max
}
func origin(s string, httpsOnly bool) bool {
	u, e := url.Parse(s)
	if e != nil || u.Hostname() == "" || u.User != nil || u.Path != "" || u.RawPath != "" || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" || u.Opaque != "" {
		return false
	}
	ip := net.ParseIP(u.Hostname())
	return u.Scheme == "https" || (!httpsOnly && u.Scheme == "http" && ip != nil && ip.IsLoopback())
}

// Require the exact schema, including exact member spelling and all fields.
// JSON aliases, nulls, duplicate members and trailing values cannot replace a
// selected identity. This also applies recursively to trust anchors and pins.
func strictJSON(raw []byte, dst any) error {
	if !utf8.Valid(raw) || !chainjson.ValidFolded(raw) {
		return errHeld
	}
	t := reflect.TypeOf(dst)
	if t.Kind() != reflect.Pointer || exactShape(raw, t.Elem()) != nil {
		return errHeld
	}
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	if d.Decode(dst) != nil {
		return errHeld
	}
	var tail any
	if d.Decode(&tail) != io.EOF {
		return errHeld
	}
	return nil
}
func exactShape(raw []byte, t reflect.Type) error {
	if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) {
		return errHeld
	}
	switch t.Kind() {
	case reflect.Struct:
		var members map[string]json.RawMessage
		if json.Unmarshal(raw, &members) != nil || len(members) != t.NumField() {
			return errHeld
		}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			key := strings.Split(f.Tag.Get("json"), ",")[0]
			child, ok := members[key]
			if !ok || exactShape(child, f.Type) != nil {
				return errHeld
			}
		}
	case reflect.Slice:
		var items []json.RawMessage
		if json.Unmarshal(raw, &items) != nil {
			return errHeld
		}
		for _, v := range items {
			if exactShape(v, t.Elem()) != nil {
				return errHeld
			}
		}
	}
	return nil
}
func (c config) pins() []filePin {
	return []filePin{c.Postgres.Password, c.Postgres.CA, c.Postgres.ClientCertificate, c.Postgres.ClientKey, c.Watcher.CA, c.Watcher.Token, c.ReviewerPrivateKey, c.HTTPToken, c.CustodyToken}
}
func (c config) policy() (satchelservice.Policy, error) {
	w, e := publicKey(c.Roles.WagerPublicKeyHex)
	if e != nil {
		return satchelservice.Policy{}, e
	}
	d, e := publicKey(c.Roles.WithdrawalPublicKeyHex)
	if e != nil {
		return satchelservice.Policy{}, e
	}
	return satchelservice.Policy{Vault: c.Vault, BettingEscrow: c.BettingEscrow, ProtectedAddresses: append([]string{}, c.ProtectedAddresses...), MaxAmountUWolo: c.MaxAmountUWolo, WithdrawalApprovalKey: d, WagerApprovalKey: w}, nil
}
func (c config) validate() error {
	if c.Version != 1 || !revisionPattern.MatchString(c.SourceRevision) || strings.Trim(c.SourceRevision, "0") == "" ||
		!validDigest(c.BinarySHA256) || !validDigest(c.IssuerPolicySHA256) || !validAddress(c.Vault) || satchel.IsKnownRoleAddress(c.Vault) ||
		!validAddress(c.BettingEscrow) || c.Vault == c.BettingEscrow || c.MaxAmountUWolo == 0 || c.MaxAmountUWolo > 1_000_000 ||
		!positive(c.FeeUWolo, 1_000_000) || !positive(c.MinimumGasReserveUWolo, 1<<63-1) || !positive(c.MinimumUnencumberedUWolo, 1<<63-1) ||
		!validDigest(c.Custody.BuildSHA256) || !validDigest(c.Custody.ConfigSHA256) || !validDigest(c.Custody.PermitSHA256) || !validDigest(c.Custody.PolicySHA256) ||
		!origin(c.Watcher.Origin, true) || !validDigest(c.Watcher.ServerSPKISHA256) || !origin(c.RPC, false) || !origin(c.REST, false) || !origin(c.WitnessRPC, false) || c.RPC == c.WitnessRPC ||
		c.TrustAnchor.Height < 1 || !digestPattern.MatchString(strings.ToLower(c.TrustAnchor.Hash)) || strings.Trim(c.TrustAnchor.Hash, "0") == "" ||
		c.TrustAnchor.PeriodSeconds < 60 || c.TrustAnchor.PeriodSeconds > 86400 || strings.TrimSpace(c.TrustAnchor.EvidenceReference) == "" || len(c.TrustAnchor.EvidenceReference) > 512 {
		return errHeld
	}
	if !rolePattern.MatchString(c.Postgres.Role) || !namePattern.MatchString(c.Postgres.Database) || c.Postgres.Port == 0 ||
		!validPGHost(c.Postgres.Host) {
		return errHeld
	}
	seen := map[string]bool{}
	for _, s := range []string{c.Roles.AccountingPublicKeyHex, c.Roles.CustodyPublicKeyHex, c.Roles.ExecutionPublicKeyHex, c.Roles.WagerPublicKeyHex, c.Roles.WithdrawalPublicKeyHex, c.Watcher.WitnessPublicKeyHex} {
		if _, e := publicKey(s); e != nil || seen[s] {
			return errHeld
		}
		seen[s] = true
	}
	addresses := map[string]bool{}
	if len(c.ProtectedAddresses) == 0 || len(c.ProtectedAddresses) > 64 {
		return errHeld
	}
	for _, a := range c.ProtectedAddresses {
		if !validAddress(a) || a == c.Vault || addresses[a] {
			return errHeld
		}
		addresses[a] = true
	}
	if !addresses[c.BettingEscrow] {
		return errHeld
	}
	paths := map[string]bool{}
	for _, p := range c.pins() {
		if !validPath(p.Path) || !validDigest(p.SHA256) || paths[p.Path] {
			return errHeld
		}
		paths[p.Path] = true
	}
	for _, p := range []string{c.JournalPath, c.ReserveCoveragePath, c.PermitPath} {
		if !validPath(p) || paths[p] {
			return errHeld
		}
		paths[p] = true
	}
	if c.RequiredProducerIDs == nil || len(c.RequiredProducerIDs) > 58 {
		return errHeld
	}
	seen = map[string]bool{}
	for _, id := range c.RequiredProducerIDs {
		if !producerPattern.MatchString(id) || seen[id] {
			return errHeld
		}
		seen[id] = true
	}
	p, e := c.policy()
	if e != nil {
		return errHeld
	}
	raw, e := json.Marshal(p)
	if e != nil || digest(raw) != c.IssuerPolicySHA256 {
		return errHeld
	}
	return nil
}
func loadConfig(path string) (config, string, error) {
	var c config
	raw, e := satchelservice.ReadPrivateFile(path, 64<<10)
	if e != nil || strictJSON(raw, &c) != nil || c.validate() != nil {
		return config{}, "", errHeld
	}
	for _, p := range c.pins() {
		if p.Path == path {
			return config{}, "", errHeld
		}
	}
	if c.JournalPath == path || c.PermitPath == path || c.ReserveCoveragePath == path {
		return config{}, "", errHeld
	}
	return c, digest(raw), nil
}
func readPinned(p filePin) ([]byte, error) {
	raw, e := satchelservice.ReadPrivateFile(p.Path, 1<<20)
	if e != nil || digest(raw) != p.SHA256 {
		wipe(raw)
		return nil, errHeld
	}
	return raw, nil
}
func readPermit(path string) ([]byte, error) { return satchelservice.ReadPrivateFile(path, 16<<10) }

const permitScope = "aoe2war/satchel/reviewer-startup/v1"

type startupPermit struct {
	Version            int    `json:"version"`
	Scope              string `json:"scope"`
	ConfigSHA256       string `json:"config_sha256"`
	BinarySHA256       string `json:"binary_sha256"`
	SourceRevision     string `json:"source_revision"`
	IssuerPolicySHA256 string `json:"issuer_policy_sha256"`
	Vault              string `json:"vault"`
	WagerPublicKeyHex  string `json:"wager_public_key_hex"`
	IssuedAt           int64  `json:"issued_at"`
	ExpiresAt          int64  `json:"expires_at"`
	Signature          string `json:"signature"`
}

func permitMessage(p startupPermit) []byte {
	raw, _ := json.Marshal([]any{permitScope, p.Version, p.Scope, p.ConfigSHA256, p.BinarySHA256, p.SourceRevision, p.IssuerPolicySHA256, p.Vault, p.WagerPublicKeyHex, p.IssuedAt, p.ExpiresAt})
	return raw
}
func verifyPermit(c config, configDigest, binaryDigest string, p startupPermit, now time.Time) bool {
	if now.IsZero() || p.Version != 1 || p.Scope != permitScope || p.ConfigSHA256 != configDigest || !validDigest(configDigest) ||
		p.BinarySHA256 != binaryDigest || binaryDigest != c.BinarySHA256 || p.SourceRevision != c.SourceRevision || p.IssuerPolicySHA256 != c.IssuerPolicySHA256 ||
		p.Vault != c.Vault || p.WagerPublicKeyHex != c.Roles.WagerPublicKeyHex || p.IssuedAt <= 0 || p.IssuedAt > now.Unix() || p.ExpiresAt <= now.Unix() || p.ExpiresAt <= p.IssuedAt || p.ExpiresAt-p.IssuedAt > 120 {
		return false
	}
	key, e := publicKey(c.Roles.ExecutionPublicKeyHex)
	if e != nil {
		return false
	}
	sig, e := base64.StdEncoding.Strict().DecodeString(p.Signature)
	return e == nil && len(sig) == ed25519.SignatureSize && base64.StdEncoding.EncodeToString(sig) == p.Signature && ed25519.Verify(key, permitMessage(p), sig)
}
