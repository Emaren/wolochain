var errHeld = errors.New("reviewer_startup_held")
var digestPattern = regexp.MustCompile(`^[a-f0-9]{64}$`)
var revisionPattern = regexp.MustCompile(`^[a-f0-9]{40}$`)
var rolePattern = regexp.MustCompile(`^satchel_reviewer_[a-z0-9_]{1,48}$`)
var namePattern = regexp.MustCompile(`^[a-zA-Z0-9_][a-zA-Z0-9_.-]{0,62}$`)
var tokenPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{48,512}$`)
var producerPattern = regexp.MustCompile(`^[a-z0-9_.-]{1,128}$`)
var hostLabelPattern = regexp.MustCompile(`^[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?$`)

// Every immutable external input is selected by both path and reviewed bytes.
